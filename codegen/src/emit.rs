/// Does a list the model holds inline as `Reals3` (`r3` as in `Slot`) have
/// more than three values?
fn too_many_reals(r3: u8, a: &Attribute) -> bool {
    match (r3, a) {
        (1, Attribute::List(l)) => l.len() > 3,
        (2, Attribute::List(l)) => l.iter().any(|e| matches!(e, Attribute::List(v) if v.len() > 3)),
        _ => false,
    }
}

/// Value-level canonical: signed-zero -0.0 -> +0.0, recursively (incl. lists).
fn canon(a: &mut Attribute) {
    match a {
        Attribute::Real(r) => { if *r == 0.0 { *r = 0.0_f64; } }
        Attribute::List(v) => { for e in v.iter_mut() { canon(e); } }
        Attribute::Typed { value, .. } => canon(value),
        _ => {}
    }
}

/// A non-standard bare scalar select member (`5.` / `'x'`) -> the standard Typed
/// literal `WIRE(value)`. Only the single-scalar-arm case (unambiguous wire) is
/// normalized here; entity refs (`#n`) and already-typed values are left alone.
fn wrap_bare_scalar(a: &mut Attribute, wire: &'static str) -> bool {
    match a {
        Attribute::Real(_) | Attribute::Integer(_) | Attribute::String(_) => {
            let inner = std::mem::replace(a, Attribute::Unset);
            *a = Attribute::Typed { type_name: wire.to_string(), value: Box::new(inner) };
            true
        }
        _ => false,
    }
}

/// Result of normalizing one slot value. Unchanged = already standard; Rewrite =
/// fixed to a standard value (kept, "fix"); Drop = non-normalizable (entity removed,
/// "drop"). The fix/drop split feeds the two surface channels (norm vs drops).
enum NormAction { Unchanged, Rewrite(Attribute, &'static str), Drop(&'static str) }

/// Slot-kind general rules (single rule per slot, output is the final standard
/// value). Value rules (int<->real) apply regardless of req; the `$`/`*` rules
/// apply per req/derived.
fn norm_attr(s: Slot, a: &Attribute) -> NormAction {
    if s.der {
        // a derived slot is always `*` on the wire; force it (drops a redundant
        // explicit value or a non-standard `()`/`$`).
        return if matches!(a, Attribute::Derived) { NormAction::Unchanged }
               else { NormAction::Rewrite(Attribute::Derived, "derived attribute reset to *") };
    }
    match (s.k, a) {
        (Sk::Real, Attribute::Integer(i)) => NormAction::Rewrite(Attribute::Real(*i as f64), "integer converted to real number"),
        (Sk::Int, Attribute::Real(r)) if r.fract() == 0.0 => {
            NormAction::Rewrite(Attribute::Integer(*r as i64), "real converted to integer")
        }
        (Sk::Int, Attribute::Real(_)) => NormAction::Drop("integer field has a fractional value"),
        (Sk::Str | Sk::Bin, Attribute::Unset) if s.req => {
            NormAction::Rewrite(Attribute::String(String::new()), "missing required text set to empty")
        }
        (Sk::Vec, Attribute::Unset) if s.req => NormAction::Rewrite(Attribute::List(Vec::new()), "missing required list set to empty"),
        (Sk::Ref, Attribute::Unset) if s.req => NormAction::Drop("required reference is missing"),
        _ => NormAction::Unchanged,
    }
}

/// Normalize one entity's attrs. Rewrites push to `warns` (norm channel); a
/// non-normalizable slot sets `drop_out` to its reason and returns false (the
/// entity is removed — nonstandard-value drop, surfaced on the drops channel).
fn norm_attrs(slots: &[Slot], attrs: &mut Vec<Attribute>, warns: &mut Vec<&'static str>, drop_out: &mut Option<&'static str>) -> bool {
    for (i, a) in attrs.iter_mut().enumerate() {
        canon(a);
        if let Some(s) = slots.get(i).copied() {
            // nested select-scalar normalization: a ref/aggregate slot whose target
            // SELECT has a single scalar arm — rewrite bare members to typed.
            if let Some(wire) = s.swire {
                match s.k {
                    Sk::Vec => {
                        if let Attribute::List(v) = a {
                            for e in v.iter_mut() {
                                if wrap_bare_scalar(e, wire) { warns.push("untyped value tagged with its type"); }
                            }
                        }
                    }
                    Sk::Ref => {
                        if wrap_bare_scalar(a, wire) { warns.push("untyped value tagged with its type"); }
                    }
                    _ => {}
                }
            }
            match norm_attr(s, a) {
                NormAction::Unchanged => {}
                NormAction::Rewrite(na, w) => { *a = na; warns.push(w); }
                NormAction::Drop(w) => { *drop_out = Some(w); return false; }
            }
            if too_many_reals(s.r3, a) {
                *drop_out = Some("list has more values than its type allows");
                return false;
            }
        }
    }
    true
}

