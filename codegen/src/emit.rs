/// Collect the EntityKey deps of a single attribute into `out` (pass-1 numbering).
/// Returns None when the attr holds no entity ref (scalar/enum/measure). When
/// `by_ref` the accessor is already a reference (a complex part binder); else it
/// is a field place needing `&`.
fn collect_deps(
    ir: &ModelIr,
    k: &Kind,
    optional: bool,
    access: &str,
    by_ref: bool,
) -> Option<String> {
    let amp = if by_ref { "" } else { "&" };
    match k {
        Kind::Ref(t) => {
            let dm = ref_method(&ir.ref_enums[t].rust);
            Some(if optional {
                format!("if let Some(r) = {amp}{access} {{ Self::deps_{dm}(r, out); }}")
            } else {
                format!("Self::deps_{dm}({amp}{access}, out);")
            })
        }
        Kind::Vec(inner) => {
            let elem = collect_deps_elem(ir, inner)?;
            Some(if optional {
                format!("if let Some(v) = {amp}{access} {{ for e in v {{ {elem} }} }}")
            } else {
                format!("for e in {amp}{access} {{ {elem} }}")
            })
        }
        _ => None,
    }
}

/// Collect EntityKey deps from a Vec element bound to `e`. None if no ref inside.
fn collect_deps_elem(ir: &ModelIr, k: &Kind) -> Option<String> {
    match k {
        Kind::Ref(t) => {
            let dm = ref_method(&ir.ref_enums[t].rust);
            Some(format!("Self::deps_{dm}(e, out);"))
        }
        Kind::Vec(inner) => {
            let inner = collect_deps_elem(ir, inner)?;
            Some(format!("for e in e {{ {inner} }}"))
        }
        _ => None,
    }
}

/// Emit `deps_of(model, any, out)`: push the EntityKey deps of an entity (simple or
/// complex part-bag). Self-edges are filtered by the driver, not here. It reads only
/// the model, so `RefGraph` calls it without a `Writer`.
fn emit_deps_of(s: &mut String, ir: &ModelIr) {
    s.push_str(
        "    pub(crate) fn deps_of(model: &StepModel, any: EntityKey, out: &mut Vec<EntityKey>) { match any {\n",
    );
    for se in &ir.simples {
        let af = arena_field(&se.rust);
        let kept = idents(&se.fields);
        let mut body = String::new();
        for (id, f) in &kept {
            if f.derived {
                continue;
            }
            if let Some(stmt) = collect_deps(
                ir,
                &f.kind,
                f.optional || f.derivable,
                &format!("it.{id}"),
                false,
            ) {
                body.push_str(&stmt);
                body.push(' ');
            }
        }
        if body.is_empty() {
            writeln!(s, "        EntityKey::{}(_) => {{}},", se.rust).unwrap();
        } else {
            writeln!(
                s,
                "        EntityKey::{}(id) => {{ let it = model.{}.get(id.0); {} }},",
                se.rust, af, body
            )
            .unwrap();
        }
    }
    if ir.has_part_bag {
        s.push_str(
            "        EntityKey::ComplexEntity(id) => { let cu = model.complex_entity_arena.get(id.0); for part in &cu.parts { match part {\n",
        );
        for p in &ir.parts {
            let kept = idents(&p.fields);
            let mut binders: Vec<String> = Vec::new();
            let mut stmts = String::new();
            for (id, f) in &kept {
                if f.derived {
                    continue;
                }
                if let Some(stmt) = collect_deps(ir, &f.kind, f.optional || f.derivable, id, true) {
                    binders.push(id.clone());
                    stmts.push_str(&stmt);
                    stmts.push(' ');
                }
            }
            if stmts.is_empty() {
                continue;
            }
            writeln!(
                s,
                "            PartialEntity::{} {{ {}, .. }} => {{ {} }},",
                p.rust,
                binders.join(", "),
                stmts
            )
            .unwrap();
        }
        s.push_str("            _ => {}\n        } } },\n");
    }
    s.push_str("    } }\n\n");
}

/// Emit `render_one(any) -> String`: render one entity line, resolving refs by
/// id-lookup (no recursion; all ids pre-assigned in pass 1).
fn emit_render_one(s: &mut String, ir: &ModelIr) {
    s.push_str("    fn render_one(&self, any: EntityKey) -> String { match any {\n");
    for se in &ir.simples {
        let af = arena_field(&se.rust);
        let kept = idents(&se.fields);
        let uses_it = kept.iter().any(|(_, f)| !f.derived);
        let mut parts: Vec<String> = Vec::new();
        for (id, f) in &kept {
            if f.derived {
                parts.push("\"*\".to_string()".to_string());
                continue;
            }
            parts.push(render_attr(
                ir,
                &f.kind,
                f.optional,
                f.derivable,
                &format!("it.{id}"),
            ));
        }
        let binder = if uses_it { "id" } else { "_" };
        let it_bind = if uses_it {
            format!("let it = self.model.{af}.get(id.0); ")
        } else {
            String::new()
        };
        writeln!(
            s,
            "        EntityKey::{}({binder}) => {{ {it_bind}let n = self.get_id(any).expect(\"id assigned\"); let kw = Self::name_of(any); let attrs: Vec<String> = vec![{}]; format!(\"#{{n}} = {{kw}}({{}});\\n\", attrs.join(\",\")) }},",
            se.rust,
            parts.join(", ")
        )
        .unwrap();
    }
    if ir.has_part_bag {
        s.push_str(
            "        EntityKey::ComplexEntity(id) => { let cu = self.model.complex_entity_arena.get(id.0); let n = self.get_id(any).expect(\"id assigned\"); let mut part_txt: Vec<String> = Vec::with_capacity(cu.parts.len()); for part in &cu.parts { part_txt.push(match part {\n",
        );
        for p in &ir.parts {
            let kept = idents(&p.fields);
            let nonderived: Vec<_> = kept.iter().filter(|(_, f)| !f.derived).collect();
            if kept.is_empty() {
                writeln!(
                    s,
                    "                PartialEntity::{} => \"{}()\".to_string(),",
                    p.rust, p.name
                )
                .unwrap();
                continue;
            }
            let binders: Vec<String> = nonderived.iter().map(|(id, _)| id.clone()).collect();
            write!(
                s,
                "                PartialEntity::{} {{ {} }} => {{",
                p.rust,
                if binders.is_empty() {
                    ".. ".to_string()
                } else {
                    format!("{}, ..", binders.join(", "))
                }
            )
            .unwrap();
            let mut rendered: Vec<String> = Vec::new();
            for (id, f) in &kept {
                if f.derived {
                    rendered.push("\"*\".to_string()".to_string());
                } else {
                    rendered.push(render_part_attr(ir, &f.kind, f.optional, f.derivable, id));
                }
            }
            write!(s, " let a: Vec<String> = vec![{}];", rendered.join(", ")).unwrap();
            writeln!(s, " format!(\"{}({{}})\", a.join(\",\")) }},", p.name).unwrap();
        }
        s.push_str(
            "            });\n        } format!(\"#{n} = ( {} );\\n\", part_txt.join(\" \")) },\n",
        );
    }
    s.push_str("    } }\n\n");
}

/// Render one attribute to a `String` expression. `access` is the field
/// accessor. An optional field renders `None` as `$`; a derivable field renders
/// `None` as `*`.
/// A `Reals3` writes like a list of reals (it reads as a slice).
fn written_as(k: &Kind) -> std::borrow::Cow<'_, Kind> {
    match k {
        Kind::Reals3 { .. } => std::borrow::Cow::Owned(Kind::Vec(Box::new(Kind::Real))),
        _ => std::borrow::Cow::Borrowed(k),
    }
}

fn render_attr(ir: &ModelIr, k: &Kind, optional: bool, derivable: bool, access: &str) -> String {
    let written = written_as(k);
    let k = &*written;
    let wrapped = optional || derivable;
    let none_tok = if derivable { "*" } else { "$" };
    match k {
        Kind::Ref(t) => {
            let re = &ir.ref_enums[t];
            if wrapped {
                format!(
                    "match &{access} {{ Some(r) => {}, None => \"{none_tok}\".to_string() }}",
                    render_ref_value(re, "r")
                )
            } else {
                render_ref_value(re, &format!("&{access}"))
            }
        }
        Kind::Vec(inner) => {
            let elem = render_vec_elem(ir, inner);
            let body = format!(
                "format!(\"({{}})\", {access}.iter().map(|e| {elem}).collect::<Vec<_>>().join(\",\"))"
            );
            if wrapped {
                format!(
                    "match &{access} {{ Some(v) => format!(\"({{}})\", v.iter().map(|e| {elem}).collect::<Vec<_>>().join(\",\")), None => \"{none_tok}\".to_string() }}"
                )
            } else {
                body
            }
        }
        scalar => {
            let body = render_scalar(ir, scalar, access);
            if wrapped {
                format!(
                    "match &{access} {{ Some(x) => {}, None => \"{none_tok}\".to_string() }}",
                    render_scalar_ref(ir, scalar, "x")
                )
            } else {
                body
            }
        }
    }
}

/// Render a ref-enum value (given by a `&{re.rust}` expression `v`) to a String
/// expr: `#n` for a single arm; `(#a,#b)` for an aggregate arm. ref-enums are
/// non-Copy, so the dispatch clones the value it hands to `emit_*`.
fn render_ref_value(re: &RefEnum, v: &str) -> String {
    let m = ref_method(&re.rust);
    let mut arms: Vec<String> = Vec::new();
    for (aggv, elt_ref, wire) in &re.aggregate {
        let em = ref_method(elt_ref);
        // named aggregate -> Typed literal `WIRE((#a,#b))`.
        arms.push(format!(
            "{rust}::{aggv}(vs) => format!(\"{wire}(({{}}))\", vs.iter().map(|e| format!(\"#{{}}\", self.id_of_{em}(e))).collect::<Vec<_>>().join(\",\")),",
            rust = re.rust
        ));
    }
    for (ev, _, wire) in &re.enum_arms {
        // named enum select member -> Typed literal `WIRE(.TOKEN.)` (token() has dots).
        arms.push(format!(
            "{rust}::{ev}(e) => format!(\"{wire}({{}})\", e.token()),",
            rust = re.rust
        ));
    }
    for (sv, sk, wire) in &re.scalar_arms {
        // named scalar select member -> always the standard Typed literal
        // `WIRE(value)` (a bare-on-read value is normalized to this on write).
        let val = match sk {
            Kind::Real => "real(*x)",
            Kind::Str => "step_str(self.model.text(*x))",
            _ => unreachable!("unsupported scalar arm kind"),
        };
        arms.push(format!(
            "{rust}::{sv}(x) => format!(\"{wire}({{}})\", {val}),",
            rust = re.rust
        ));
    }
    if arms.is_empty() {
        format!("format!(\"#{{}}\", self.id_of_{m}({v}))")
    } else {
        format!(
            "match {v} {{ {} other => format!(\"#{{}}\", self.id_of_{m}(other)) }}",
            arms.join(" ")
        )
    }
}

fn render_scalar(_ir: &ModelIr, k: &Kind, access: &str) -> String {
    match k {
        Kind::Real => format!("real({access})"),
        Kind::Int => format!("format!(\"{{}}\", {access})"),
        Kind::Str => format!("step_str(self.model.text({access}))"),
        Kind::Bool => format!("(if {access} {{ \".T.\" }} else {{ \".F.\" }}).to_string()"),
        Kind::Logical => format!("{access}.token().to_string()"),
        Kind::Binary => format!("format!(\"'{{}}'\", {access})"),
        Kind::MeasureSelect(_) => format!("measure(self.model, &{access})"),
        Kind::StringSelect(_) => format!("string_select(self.model, &{access})"),
        Kind::IntSelect(_) => format!("int_measure(self.model, &{access})"),
        Kind::Enum(_) => format!("{access}.token().to_string()"),
        _ => unreachable!(),
    }
}

/// Same as render_scalar but for a `&T` binding (optional Some case).
fn render_scalar_ref(_ir: &ModelIr, k: &Kind, access: &str) -> String {
    match k {
        Kind::Real => format!("real(*{access})"),
        Kind::Int => format!("format!(\"{{}}\", {access})"),
        Kind::Str => format!("step_str(self.model.text(*{access}))"),
        Kind::Bool => format!("(if *{access} {{ \".T.\" }} else {{ \".F.\" }}).to_string()"),
        Kind::Logical => format!("{access}.token().to_string()"),
        Kind::Binary => format!("format!(\"'{{}}'\", {access})"),
        Kind::MeasureSelect(_) => format!("measure(self.model, {access})"),
        Kind::StringSelect(_) => format!("string_select(self.model, {access})"),
        Kind::IntSelect(_) => format!("int_measure(self.model, {access})"),
        Kind::Enum(_) => format!("{access}.token().to_string()"),
        _ => unreachable!(),
    }
}

fn render_vec_elem(ir: &ModelIr, inner: &Kind) -> String {
    let written = written_as(inner);
    let inner = &*written;
    match inner {
        Kind::Ref(t) => {
            let re = &ir.ref_enums[t];
            render_ref_value(re, "e")
        }
        Kind::Vec(i2) => {
            // nested list (e.g. control_points_list grid). Rebind inner elem to `e`.
            let inner_elem = render_vec_elem(ir, i2);
            format!(
                "{{ let row: Vec<String> = e.iter().map(|e| {inner_elem}).collect(); format!(\"({{}})\", row.join(\",\")) }}"
            )
        }
        Kind::Real => "real(*e)".to_string(),
        Kind::Int => "format!(\"{e}\")".to_string(),
        Kind::Str => "step_str(self.model.text(*e))".to_string(),
        Kind::Logical => "e.token().to_string()".to_string(),
        Kind::Enum(_) => "e.token().to_string()".to_string(),
        Kind::MeasureSelect(_) => "measure(self.model, e)".to_string(),
        Kind::StringSelect(_) => "string_select(self.model, e)".to_string(),
        Kind::IntSelect(_) => "int_measure(self.model, e)".to_string(),
        _ => "real(*e)".to_string(),
    }
}

fn ref_method(re_rust: &str) -> String {
    // CurveRef -> ref_curve  (method name for the ref dispatch)
    let base = re_rust.trim_end_matches("Ref");
    let mut out = String::new();
    for (i, c) in base.chars().enumerate() {
        if c.is_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(c.to_ascii_lowercase());
    }
    format!("ref_{out}")
}

/// Emit `id_of_<ref>`: ref-enum -> the step_id already assigned to its target
/// (lookup in the arena `_ids` caches). The iterative replacement for the old
/// recursive emit dispatch. Aggregate/enum/scalar arms are rendered inline by
/// render_ref_value, so they never reach single-id lookup.
fn emit_ref_id_of(s: &mut String, re: &RefEnum) {
    writeln!(
        s,
        "    fn id_of_{}(&self, r: &{}) -> u64 {{ match r {{",
        ref_method(&re.rust),
        re.rust
    )
    .unwrap();
    for (variant, target) in &re.simple_arms {
        writeln!(
            s,
            "        {}::{variant}(i) => self.{}[i.0 as usize].expect(\"dep id assigned\"),",
            re.rust,
            ids_field(target)
        )
        .unwrap();
    }
    if re.has_complex {
        writeln!(
            s,
            "        {}::Complex(i) => self.complex_ids[i.0 as usize].expect(\"dep id assigned\"),",
            re.rust
        )
        .unwrap();
    }
    for (variant, _, _) in &re.aggregate {
        writeln!(
            s,
            "        {}::{variant}(_) => panic!(\"aggregate via single id_of\"),",
            re.rust
        )
        .unwrap();
    }
    for (variant, _, _) in &re.enum_arms {
        writeln!(
            s,
            "        {}::{variant}(_) => panic!(\"enum via single id_of\"),",
            re.rust
        )
        .unwrap();
    }
    for (variant, _, _) in &re.scalar_arms {
        writeln!(
            s,
            "        {}::{variant}(_) => panic!(\"scalar via single id_of\"),",
            re.rust
        )
        .unwrap();
    }
    if re.simple_arms.is_empty()
        && re.aggregate.is_empty()
        && re.enum_arms.is_empty()
        && re.scalar_arms.is_empty()
        && !re.has_complex
    {
        writeln!(
            s,
            "        {}::Unresolved => panic!(\"id_of unresolved\"),",
            re.rust
        )
        .unwrap();
    }
    s.push_str("    } }\n\n");
}

/// Emit `deps_<ref>`: ref-enum -> push its EntityKey deps (for pass-1 numbering).
/// Aggregate arms recurse into element refs; enum/scalar arms carry no entity dep.
fn emit_ref_deps(s: &mut String, re: &RefEnum) {
    writeln!(
        s,
        "    fn deps_{}(r: &{}, out: &mut Vec<EntityKey>) {{ match r {{",
        ref_method(&re.rust),
        re.rust
    )
    .unwrap();
    for (variant, target) in &re.simple_arms {
        writeln!(
            s,
            "        {}::{variant}(i) => out.push(EntityKey::{}(*i)),",
            re.rust, target
        )
        .unwrap();
    }
    if re.has_complex {
        writeln!(
            s,
            "        {}::Complex(i) => out.push(EntityKey::ComplexEntity(*i)),",
            re.rust
        )
        .unwrap();
    }
    for (variant, elt_ref, _) in &re.aggregate {
        writeln!(
            s,
            "        {}::{variant}(vs) => {{ for e in vs {{ Self::deps_{}(e, out); }} }},",
            re.rust,
            ref_method(elt_ref)
        )
        .unwrap();
    }
    for (variant, _, _) in &re.enum_arms {
        writeln!(s, "        {}::{variant}(_) => {{}},", re.rust).unwrap();
    }
    for (variant, _, _) in &re.scalar_arms {
        writeln!(s, "        {}::{variant}(_) => {{}},", re.rust).unwrap();
    }
    if re.simple_arms.is_empty()
        && re.aggregate.is_empty()
        && re.enum_arms.is_empty()
        && re.scalar_arms.is_empty()
        && !re.has_complex
    {
        writeln!(s, "        {}::Unresolved => {{}},", re.rust).unwrap();
    }
    s.push_str("    } }\n\n");
}

/// Emit `emit_all`: iterative 2-pass topo write. Pass 1 assigns step_ids by an
/// explicit-stack post-order DFS (deps before dependents; self-edges skipped;
/// multi-node cycle back-edges pre-numbered as forward-refs). Pass 2 renders in
/// id order. No recursion -> stack depth is independent of graph depth.
/// Writer primitives: `name_of` (EntityKey → STEP keyword), `all_ids` (every
/// node in arena order).
fn emit_writer_primitives(s: &mut String, ir: &ModelIr) {
    // name_of: EntityKey -> STEP keyword (same source as render_one's literal).
    s.push_str("    pub(crate) fn name_of(any: EntityKey) -> &'static str { match any {\n");
    for se in &ir.simples {
        writeln!(s, "        EntityKey::{}(_) => \"{}\",", se.rust, se.name).unwrap();
    }
    if ir.has_part_bag {
        // complex = no single keyword; rendered from its parts.
        s.push_str("        EntityKey::ComplexEntity(_) => \"\",\n");
    }
    s.push_str("    } }\n\n");

    // all_ids: every node, arena order (the former emit_all roots block).
    s.push_str("    pub(crate) fn all_ids(&self) -> Vec<EntityKey> {\n        let mut roots: Vec<EntityKey> = Vec::new();\n");
    if ir.has_part_bag {
        s.push_str("        for i in 0..self.model.complex_entity_arena.items.len() as u32 { roots.push(EntityKey::ComplexEntity(ComplexEntityId(i))); }\n");
    }
    for se in &ir.simples {
        writeln!(
            s,
            "        for i in 0..self.model.{}.items.len() as u32 {{ roots.push(EntityKey::{}({}Id(i))); }}",
            arena_field(&se.rust),
            se.rust,
            se.rust
        )
        .unwrap();
    }
    s.push_str("        roots\n    }\n\n");
}

/// emit_all: every entity, `dfs_render` order. roots come from `all_ids`
/// (emit_writer_primitives).
fn emit_all_iter(s: &mut String, _ir: &ModelIr) {
    s.push_str(
        r#"    /// Write every entity's DATA line to `w`, a chunk at a time.
    pub fn emit_all(self, w: &mut dyn std::io::Write) -> std::io::Result<()> {
        let roots = self.all_ids();
        self.dfs_render(roots, w)
    }

    fn dfs_render(mut self, roots: Vec<EntityKey>, w: &mut dyn std::io::Write) -> std::io::Result<()> {
        let mut order: Vec<EntityKey> = Vec::new();
        let mut stack: Vec<(EntityKey, bool)> = Vec::new();
        let mut on_path: std::collections::HashSet<EntityKey> = std::collections::HashSet::new();
        for root in roots {
            if self.get_id(root).is_some() { continue; }
            stack.push((root, false));
            while let Some((any, post)) = stack.pop() {
                if post {
                    on_path.remove(&any);
                    if self.get_id(any).is_none() {
                        let n = self.fresh();
                        self.set_id(any, n);
                        order.push(any);
                    }
                    continue;
                }
                if self.get_id(any).is_some() { continue; }
                if on_path.contains(&any) {
                    // multi-node cycle back-edge: pre-number as a forward-ref.
                    let n = self.fresh();
                    self.set_id(any, n);
                    order.push(any);
                    continue;
                }
                on_path.insert(any);
                stack.push((any, true));
                let mut deps: Vec<EntityKey> = Vec::new();
                Self::deps_of(self.model, any, &mut deps);
                for d in deps.into_iter().rev() {
                    if d == any { continue; }
                    if self.get_id(d).is_some() { continue; }
                    stack.push((d, false));
                }
            }
        }
        for any in &order {
            let line = self.render_one(*any);
            self.out.push_str(&line);
            if self.out.len() >= CHUNK {
                w.write_all(self.out.as_bytes())?;
                self.out.clear();
            }
        }
        w.write_all(self.out.as_bytes())
    }
}

"#,
    );
}

/// Render a complex part attribute (the binder `id` is a `&T` reference).
fn render_part_attr(ir: &ModelIr, k: &Kind, optional: bool, derivable: bool, id: &str) -> String {
    let written = written_as(k);
    let k = &*written;
    let wrapped = optional || derivable;
    let none_tok = if derivable { "*" } else { "$" };
    match k {
        Kind::Ref(t) => {
            let re = &ir.ref_enums[t];
            if wrapped {
                format!(
                    "match {id} {{ Some(r) => {}, None => \"{none_tok}\".to_string() }}",
                    render_ref_value(re, "r")
                )
            } else {
                render_ref_value(re, id)
            }
        }
        Kind::Vec(inner) => {
            let elem = render_vec_elem(ir, inner);
            if wrapped {
                format!(
                    "match {id} {{ Some(v) => format!(\"({{}})\", v.iter().map(|e| {elem}).collect::<Vec<_>>().join(\",\")), None => \"{none_tok}\".to_string() }}"
                )
            } else {
                format!(
                    "format!(\"({{}})\", {id}.iter().map(|e| {elem}).collect::<Vec<_>>().join(\",\"))"
                )
            }
        }
        scalar => {
            if wrapped {
                format!(
                    "match {id} {{ Some(x) => {}, None => \"{none_tok}\".to_string() }}",
                    render_scalar_ref(ir, scalar, "x")
                )
            } else {
                render_scalar_ref(ir, scalar, id)
            }
        }
    }
}

// ===========================================================================
// normalize.rs — strict-input normalization (slot-kind general rules).
// Runs on each raw entity BEFORE the strict read: rewrites non-standard values
// to standard (record a NormCase note), or — when not normalizable (required
// ref = `$`) — drops the entity (its referrers cascade-drop via the drop pass).
// The model/read stay strict; nothing here bends them.
// ===========================================================================

/// Top-level slot kind tag for the normalize rule table.
fn sk_variant(k: &Kind) -> &'static str {
    match k {
        Kind::Real => "Real",
        Kind::Int => "Int",
        Kind::Str => "Str",
        Kind::Binary => "Bin",
        Kind::Bool => "Bool",
        Kind::Logical => "Log",
        Kind::Enum(_) => "Enum",
        Kind::Ref(_) => "Ref",
        Kind::Vec(_) | Kind::Reals3 { .. } => "Vec",
        Kind::MeasureSelect(_) => "Meas",
        // string-select required `$` normalizes to "" (read as bare).
        Kind::StringSelect(_) => "Str",
        // int-select: same Unchanged normalize as measure; integer is preserved
        // by read_int_measure_value / int_measure (no int->real coercion).
        Kind::IntSelect(_) => "Meas",
    }
}

/// The UPPER wire name to normalize a bare scalar member to, for a ref/aggregate
/// slot whose target SELECT has exactly one scalar arm (unambiguous). None
/// otherwise (no scalar arm, or >=2 — a bare literal would be ambiguous).
fn scalar_wire_of(ir: &ModelIr, k: &Kind) -> Option<String> {
    let target = match k {
        Kind::Ref(t) => t,
        Kind::Vec(inner) => match inner.as_ref() {
            Kind::Ref(t) => t,
            _ => return None,
        },
        _ => return None,
    };
    match ir.ref_enums.get(target)?.scalar_arms.as_slice() {
        [(_, _, wire)] => Some(wire.clone()),
        _ => None,
    }
}

/// Emit a `fn {fname}({param}) -> &'static [RefSlot]` table: one RefSlot per ref
/// slot (`Ref` / `Vec<Ref>`), carrying the slot index, the admitted target types'
/// SIMPLE_NAMES indices (the ref-enum's simple arms), complex-target flag, and
/// vec flag. Non-ref slots are omitted. `ents` yields each entity's match
/// pattern (a SIMPLE_NAMES index or a quoted part name) with its fields.
fn emit_ref_slot_table<'a>(
    s: &mut String,
    fname: &str,
    param: &str,
    ir: &ModelIr,
    rust_to_index: &std::collections::HashMap<&str, usize>,
    ents: impl Iterator<Item = (usize, &'a Vec<Field>)>,
) {
    writeln!(s, "pub fn {fname}({param}: u16) -> &'static [RefSlot] {{").unwrap();
    writeln!(s, "    match {param} {{").unwrap();
    for (name, fields) in ents {
        let slots: Vec<String> = fields
            .iter()
            .enumerate()
            .filter_map(|(idx, f)| {
                let (target, is_vec) = match &f.kind {
                    Kind::Ref(t) => (t.as_str(), false),
                    Kind::Vec(inner) => match inner.as_ref() {
                        Kind::Ref(t) => (t.as_str(), true),
                        _ => return None,
                    },
                    _ => return None,
                };
                let re = ir.ref_enums.get(target)?;
                let mut allowed: Vec<usize> = re
                    .simple_arms
                    .iter()
                    .filter_map(|(_, rust)| rust_to_index.get(rust.as_str()).copied())
                    .collect();
                allowed.sort_unstable();
                allowed.dedup();
                let allowed: Vec<String> = allowed.iter().map(usize::to_string).collect();
                Some(format!(
                    "RefSlot{{idx:{idx},name:\"{}\",allowed:&[{}],complex_ok:{},is_vec:{is_vec}}}",
                    f.name,
                    allowed.join(","),
                    re.has_complex,
                ))
            })
            .collect();
        if !slots.is_empty() {
            writeln!(s, "        {} => &[{}],", name, slots.join(",")).unwrap();
        }
    }
    s.push_str("        _ => &[],\n    }\n}\n\n");
}

/// `fn {fname}({param}: u16) -> &'static [u16]`: the attribute positions of
/// the fields resolved in pass 2 (counting derived slots, as the wire does).
fn emit_ref_field_slots<'a>(
    s: &mut String,
    fname: &str,
    param: &str,
    ents: impl Iterator<Item = &'a Vec<Field>>,
) {
    writeln!(s, "pub fn {fname}({param}: u16) -> &'static [u16] {{").unwrap();
    writeln!(s, "    match {param} {{").unwrap();
    for (i, fields) in ents.enumerate() {
        let slots: Vec<String> = fields
            .iter()
            .enumerate()
            .filter(|(_, f)| !f.derived && has_ref(&f.kind))
            .map(|(idx, _)| idx.to_string())
            .collect();
        if !slots.is_empty() {
            writeln!(s, "        {i} => &[{}],", slots.join(",")).unwrap();
        }
    }
    s.push_str("        _ => &[],\n    }\n}\n\n");
}

fn emit_slot_table<'a>(
    s: &mut String,
    fname: &str,
    ir: &ModelIr,
    simple: bool,
    ents: impl Iterator<Item = (&'a String, &'a Vec<Field>)>,
) {
    writeln!(s, "fn {fname}(n: &str) -> &'static [Slot] {{").unwrap();
    s.push_str("    match n {\n");
    for (name, fields) in ents {
        let slots: Vec<String> = fields
            .iter()
            .map(|f| {
                let k = sk_variant(&f.kind);
                // A `derivable` field is `*` only in the COMPLEX (part-bag) form,
                // where a deriving sibling is present; in the STANDALONE (simple)
                // form it is an explicit, required value. So in simple_slots a
                // derivable field is required (a non-standard `$` normalizes like
                // any required field, e.g. a required string `$`); in part_slots it stays
                // non-required (the `*` case).
                let req = if simple {
                    !f.optional
                } else {
                    !(f.optional || f.derivable)
                };
                let swire = match scalar_wire_of(ir, &f.kind) {
                    Some(w) => format!("Some(\"{w}\")"),
                    None => "None".to_string(),
                };
                // Reals held inline (`Reals3`): 1 = the slot's list, 2 = each
                // list in the slot's list.
                let r3 = match &f.kind {
                    Kind::Reals3 { .. } => 1,
                    Kind::Vec(inner) if matches!(inner.as_ref(), Kind::Reals3 { .. }) => 2,
                    _ => 0,
                };
                format!(
                    "Slot{{k:Sk::{k},req:{req},der:{},swire:{swire},r3:{r3}}}",
                    f.derived
                )
            })
            .collect();
        writeln!(s, "        \"{}\" => &[{}],", name, slots.join(",")).unwrap();
    }
    s.push_str("        _ => &[],\n    }\n}\n\n");
}

